/// Escala de espaçamento do BRUT. Base 4.
abstract final class BrutSpacing {
  static const double xs = 4;
  static const double sm = 8;
  static const double md = 12;
  static const double lg = 16;
  static const double xl = 24;
  static const double xxl = 32;
}

/// Espessura padrão do traço brutalista. Sem radius, sem sombra.
abstract final class BrutStroke {
  static const double thin = 1.5;
  static const double regular = 2;
  static const double bold = 3;
}
